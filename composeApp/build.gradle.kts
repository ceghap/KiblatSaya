import org.jetbrains.kotlin.gradle.ExperimentalKotlinGradlePluginApi
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.android.application)
    alias(libs.plugins.compose.multiplatform)
    alias(libs.plugins.compose.compiler)
}

val appVersionName = libs.versions.app.versionName.get()
val appVersionCode = libs.versions.app.versionCode.get().toInt()

val generateAppBuildInfo = tasks.register("generateAppBuildInfo") {
    val outputDir = layout.buildDirectory.dir("generated/source/buildInfo/commonMain/kotlin")
    inputs.property("versionName", appVersionName)
    inputs.property("versionCode", appVersionCode)
    outputs.dir(outputDir)

    doLast {
        val file = outputDir.get().file("com/kiblatsaya/app/core/AppBuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            package com.kiblatsaya.app.core

            /**
             * Automatically generated by Gradle build task from gradle/libs.versions.toml.
             * Do not edit manually.
             */
            object AppBuildInfo {
                const val VERSION_NAME = "$appVersionName"
                const val VERSION_CODE = $appVersionCode
                const val VERSION_DISPLAY = "v$appVersionName"
            }
            """.trimIndent()
        )
    }
}

