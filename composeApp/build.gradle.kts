            implementation(kotlin("test"))
        }
    }
}

android {
    namespace = "com.kiblatsaya.app"
    compileSdk = libs.versions.android.compileSdk.get().toInt()

    defaultConfig {
        applicationId = "com.kiblatsaya.app"
        minSdk = libs.versions.android.minSdk.get().toInt()
        targetSdk = libs.versions.android.targetSdk.get().toInt()
        versionCode = appVersionCode
        versionName = appVersionName
    }

    signingConfigs {
        create("release") {
            storeFile = file("kiblatsaya-release.jks")
            storePassword = System.getenv("KEYSTORE_PASSWORD") ?: "kiblatsaya2026"
            keyAlias = System.getenv("KEY_ALIAS") ?: "kiblatsaya"
            keyPassword = System.getenv("KEY_PASSWORD") ?: "kiblatsaya2026"
