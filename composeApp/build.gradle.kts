    }
}

val distDir = rootProject.file("dist")

tasks.register<Copy>("copyReleaseArtifactsToDist") {
    dependsOn("bundleRelease", "assembleRelease")
    from(layout.buildDirectory.file("outputs/bundle/release/composeApp-release.aab")) {
        rename { "KiblatSaya-v$appVersionName.aab" }
    }
    from(layout.buildDirectory.file("outputs/apk/release/composeApp-release-unsigned.apk")) {
        rename { "KiblatSaya-v$appVersionName.apk" }
    }
    from(layout.buildDirectory.file("outputs/apk/release/composeApp-release.apk")) {
        rename { "KiblatSaya-v$appVersionName.apk" }
    }
    into(distDir)
}

tasks.register<Copy>("copyDebugArtifactsToDist") {
    dependsOn("assembleDebug")
    from(layout.buildDirectory.file("outputs/apk/debug/composeApp-debug.apk")) {
        rename { "KiblatSaya-v$appVersionName-debug.apk" }
    }
    into(distDir)
}

tasks.register("distributeRelease") {
    group = "distribution"
    description = "Builds release APK and AAB and copies them into root dist/ directory."
    dependsOn("copyReleaseArtifactsToDist")
}

tasks.register("distributeDebug") {
    group = "distribution"
    description = "Builds debug APK and copies it into root dist/ directory."
    dependsOn("copyDebugArtifactsToDist")
}
