val appVersionName = libs.versions.app.versionName.get()
val wearVersionCode = libs.versions.app.wearVersionCode.get().toInt()

val buildInfoDir = layout.buildDirectory.dir("generated/source/buildInfo/main/kotlin")

val generateWearBuildInfo = tasks.register("generateWearBuildInfo") {
    inputs.property("versionName", appVersionName)
    inputs.property("versionCode", wearVersionCode)
    outputs.dir(buildInfoDir)

    doLast {
        val file = buildInfoDir.get().file("com/kiblatsaya/app/wear/core/WearBuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            package com.kiblatsaya.app.wear.core

            /**
             * Automatically generated by Gradle build task. Do not edit manually.
             */
            object WearBuildInfo {
                const val VERSION_NAME = "$appVersionName"
                const val VERSION_CODE = $wearVersionCode
                const val VERSION_DISPLAY = "v$appVersionName"
            }
            """.trimIndent()
        )
    }
}

tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompile>().configureEach {
    dependsOn(generateWearBuildInfo)
}

