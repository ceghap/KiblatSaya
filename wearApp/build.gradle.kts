val distDir = rootProject.file("dist")

tasks.register<Copy>("copyWearReleaseArtifactsToDist") {
    dependsOn("bundleRelease", "assembleRelease")
    from(layout.buildDirectory.file("outputs/bundle/release/wearApp-release.aab")) {
        rename { "KiblatSaya-WearOS-v$appVersionName.aab" }
    }
    from(layout.buildDirectory.file("outputs/apk/release/wearApp-release.apk")) {
        rename { "KiblatSaya-WearOS-v$appVersionName.apk" }
    }
    into(distDir)
}

tasks.register<Copy>("copyWearDebugArtifactsToDist") {
    dependsOn("assembleDebug")
    from(layout.buildDirectory.file("outputs/apk/debug/wearApp-debug.apk")) {
        rename { "KiblatSaya-WearOS-v$appVersionName-debug.apk" }
    }
    into(distDir)
}

tasks.register("distributeRelease") {
    group = "distribution"
    description = "Builds Wear OS release APK and AAB and copies them to dist/."
    dependsOn("copyWearReleaseArtifactsToDist")
}

tasks.register("distributeDebug") {
    group = "distribution"
    description = "Builds Wear OS debug APK and copies it to dist/."
    dependsOn("copyWearDebugArtifactsToDist")
}
